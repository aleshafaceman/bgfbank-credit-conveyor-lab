/**
 * Общие помощники браузерных проверок поверхностей.
 *
 * Здесь лежит только то, что иначе копировалось бы в каждый чек байт в байт:
 * причина падения waitFor и строгая проверка «страница отработала без сбоев».
 * Чек подключает модуль и заворачивает помощник в замыкание со своими `s` и
 * `ok`, поэтому места вызовов в чеках остаются прежними: noFailures('текст').
 *
 * Внешних зависимостей нет; модуль не является поверхностью и в карте SURFACES
 * раннера не значится.
 *
 * Контракт: module.exports = { why, noFailures }.
 */

'use strict';

/* Причина падения waitFor: waitFor возвращает { ok, error, message }, и без
   message FAIL «очередь отрисована» не отличить от «элемента нет» — настоящая
   ошибка страницы выглядела бы как «условие не наступило». */
function why(r) {
  return r && r.message ? ' — ' + r.message : '';
}

/*
 * Строгая проверка «страница отработала без сбоев».
 *
 * В отличие от __t.visibleErrors() (ищет .err.on, которых на поверхностях
 * просто нет в разметке, и потому такое утверждение не может упасть никогда)
 * список наполняет сам браузер: непойманное исключение, необработанный отказ
 * промиса или alert() делают проверку красной. Монитор ставится обвязкой
 * (FAILURE_MONITOR_PARTS в scripts/lib/browser-check.js).
 *
 * Наличие монитора — часть утверждения: если он не поставился, пустой список
 * означал бы не «сбоев нет», а «сбои никто не считал».
 *
 * ГРАНИЦЫ МОНИТОРА (не считать его сильнее, чем он есть):
 *  1. Он стоит только на подключённом target'е: ошибки в ДОЧЕРНИХ ОКНАХ и
 *     iframe в список не попадают. Проводку таких окон проверяют отдельно —
 *     шпионом за window.open (см. deal-ops.js).
 *  2. Внешний ресурс даёт ЛОЖНЫЙ сбой: поверхности подключают шрифты с
 *     fonts.googleapis.com, и на машине без доступа к сети это честное
 *     «uncaught error» в списке. Если проверка упала именно на
 *     fonts.googleapis.com — причина в сети, а не в поверхности.
 *  3. Проглоченные try/catch исключения в список не попадают по определению.
 *
 * Проверка НАКОПИТЕЛЬНАЯ: список живёт до __t.resetFailures(). Перед действием,
 * с которым связана проверка, чек обязан очистить список сам — иначе одиночный
 * сбой в одном действии покрасит и все последующие утверждения, и разбираться
 * придётся дольше, чем чинить.
 */
async function noFailures(s, ok, msg) {
  const state = await s.eval('return (function() { try {' +
    ' return { list: __t.failures(), monitor: window.__bgfMonitor || null };' +
    ' } catch (e) { return { error: e.message }; } })()');
  if (state.error) return ok(false, msg + ' (монитор сбоев недоступен: ' + state.error + ')');
  const list = Array.isArray(state.list) ? state.list : [];
  const installed = !!(state.monitor && state.monitor.error === true &&
    state.monitor.rejection === true && state.monitor.alert === true);
  return ok(installed && list.length === 0,
    msg + ' (' + (installed ? '' : 'монитор сбоев установлен не полностью: ' +
      JSON.stringify(state.monitor) + '; ') +
    (list.length ? list.join(' | ') : 'сбоев нет') + ')');
}

module.exports = { why: why, noFailures: noFailures };
